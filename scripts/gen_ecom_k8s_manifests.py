#!/usr/bin/env python3
"""Generate the e-commerce k8s manifests.

The ecom layer shipped 8 services with Dockerfiles but no manifests at all
(P2-1: "code written, delivery not wired up"). Writing 8 near-identical
~90-line YAML files by hand invites drift — a wrong database name or a missing
secret is invisible until a pod fails to start — so the per-service facts are
derived from each service's own `application.yml` and checked against the table
below. Any mismatch fails the run instead of emitting a wrong manifest.

Run from the repo root:

    python3 scripts/gen_ecom_k8s_manifests.py          # write the manifests
    python3 scripts/gen_ecom_k8s_manifests.py --check  # verify they are up to date

`--check` makes it usable as a CI guard: it regenerates in memory and compares
against the files on disk.
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path


@dataclass(frozen=True)
class Service:
    module: str          # directory under ecom/
    app: str             # spring.application.name == k8s resource name
    port: int
    # The ecom layer SHARES databases, so the name cannot be derived from the
    # service name: ecom-member->db_user, ecom-payment->db_finance,
    # ecom-mall/ecom-order-center->db_order, ecom-fulfillment->db_warehouse.
    database: str | None
    elasticsearch: bool = False
    clickhouse: bool = False


SERVICES = [
    Service("member", "ecom-member", 8302, "db_user"),
    Service("promotion", "ecom-promotion", 8303, "db_promotion"),
    Service("payment", "ecom-payment", 8304, "db_finance"),
    Service("order-center", "ecom-order-center", 8305, "db_order"),
    Service("mall", "ecom-mall", 8301, "db_order"),
    Service("fulfillment", "ecom-fulfillment", 8306, "db_warehouse"),
    # ecom-search keeps its index in Elasticsearch; it has no relational datasource.
    Service("search", "ecom-search", 8307, None, elasticsearch=True),
    Service("analytics", "ecom-analytics", 8308, "db_analytics", clickhouse=True),
]

# (env var, configmap key) — mirrors the keys defined by the scm-config ConfigMap.
CONFIGMAP = [
    ("NACOS_SERVER_ADDR", "nacos-server"),
    ("NACOS_NAMESPACE", "nacos-namespace"),
    ("DB_HOST", "db-host"),
    ("REDIS_HOST", "redis-host"),
    ("KAFKA_BOOTSTRAP_SERVERS", "kafka-bootstrap"),
    ("SEATA_SERVER_ADDR", "seata-server"),
]

SECRETS = [
    ("DB_USERNAME", "db-username"),
    ("DB_PASSWORD", "db-password"),
    ("JWT_SECRET", "jwt-secret"),
    ("API_SECRET_INTERNAL_SERVICE", "api-secret-internal-service"),
    ("REDIS_PASSWORD", "redis-password"),
]

HEADER = """\
# Generated by scripts/gen_ecom_k8s_manifests.py — do not edit by hand.
# Edits are overwritten; change the generator (or the service's application.yml)
# and regenerate so the manifest cannot drift from the code.
"""


def render(svc: Service) -> str:
    lines: list[str] = [HEADER.rstrip("\n"), "---"]
    lines += [
        "apiVersion: apps/v1",
        "kind: Deployment",
        "metadata:",
        f"  name: {svc.app}",
        "  namespace: scm-platform",
        "  labels:",
        f"    app: {svc.app}",
        "    tier: ecommerce",
        "spec:",
        "  replicas: 2",
        "  selector:",
        "    matchLabels:",
        f"      app: {svc.app}",
        "  template:",
        "    metadata:",
        "      labels:",
        f"        app: {svc.app}",
        "      annotations:",
        '        prometheus.io/scrape: "true"',
        f'        prometheus.io/port: "{svc.port}"',
        "    spec:",
        "      containers:",
        f"        - name: {svc.app}",
        f"          image: cognora-aura-platform/{svc.app}:latest",
        "          ports:",
        f"            - containerPort: {svc.port}",
        "              name: http",
        "          env:",
        "            - name: SPRING_PROFILES_ACTIVE",
        '              value: "kubernetes"',
    ]

    for env_name, key in CONFIGMAP:
        # ecom-search has no relational datasource, so it does not need DB_HOST.
        if svc.database is None and env_name == "DB_HOST":
            continue
        lines += [
            f"            - name: {env_name}",
            "              valueFrom:",
            "                configMapKeyRef:",
            "                  name: scm-config",
            f"                  key: {key}",
        ]

    if svc.elasticsearch:
        lines += [
            "            - name: ELASTICSEARCH_URIS",
            "              valueFrom:",
            "                configMapKeyRef:",
            "                  name: scm-config",
            "                  key: elasticsearch-uris",
        ]
    if svc.clickhouse:
        lines += [
            "            - name: CH_HOST",
            "              valueFrom:",
            "                configMapKeyRef:",
            "                  name: scm-config",
            "                  key: clickhouse-host",
        ]

    for env_name, key in SECRETS:
        if svc.database is None and env_name in ("DB_USERNAME", "DB_PASSWORD"):
            continue
        lines += [
            f"            - name: {env_name}",
            "              valueFrom:",
            "                secretKeyRef:",
            "                  name: scm-secrets",
            f"                  key: {key}",
        ]

    if svc.database is not None:
        lines += [
            "            # The ecom layer shares databases, so the database name is pinned here",
            "            # rather than derived from the service name. $(DB_HOST) expands the",
            "            # ConfigMap value above, so the host stays defined in exactly one place.",
            "            - name: SPRING_DATASOURCE_URL",
            f'              value: "jdbc:postgresql://$(DB_HOST)/{svc.database}?stringtype=unspecified"',
        ]

    lines += [
        "            - name: JAVA_OPTS",
        '              value: "-Xms256m -Xmx512m -XX:+UseG1GC"',
        "          resources:",
        "            requests:",
        '              cpu: "250m"',
        '              memory: "384Mi"',
        "            limits:",
        '              cpu: "1000m"',
        '              memory: "1Gi"',
        "          livenessProbe:",
        "            httpGet:",
        "              path: /actuator/health",
        f"              port: {svc.port}",
        "            initialDelaySeconds: 60",
        "            periodSeconds: 10",
        "          readinessProbe:",
        "            httpGet:",
        "              path: /actuator/health",
        f"              port: {svc.port}",
        "            initialDelaySeconds: 30",
        "            periodSeconds: 5",
        "---",
        "apiVersion: v1",
        "kind: Service",
        "metadata:",
        f"  name: {svc.app}",
        "  namespace: scm-platform",
        "spec:",
        "  selector:",
        f"    app: {svc.app}",
        "  ports:",
        f"    - port: {svc.port}",
        f"      targetPort: {svc.port}",
        "      name: http",
        "  type: ClusterIP",
        "",
    ]
    return "\n".join(lines)


def verify(root: Path, svc: Service) -> list[str]:
    """Cross-check the table against the service's application.yml."""
    problems: list[str] = []
    cfg = root / "ecom" / svc.module / "service" / "src" / "main" / "resources" / "application.yml"
    if not cfg.exists():
        return [f"{svc.app}: missing {cfg.relative_to(root)}"]
    text = cfg.read_text(encoding="utf-8", errors="replace")

    port_match = re.search(r"^\s{2}port:\s*(\d+)", text, re.M)
    if not port_match:
        problems.append(f"{svc.app}: no server.port in {cfg.relative_to(root)}")
    elif int(port_match.group(1)) != svc.port:
        problems.append(
            f"{svc.app}: table says port {svc.port}, application.yml says {port_match.group(1)}"
        )

    if svc.database is None:
        if re.search(r"^\s{4}datasource:", text, re.M):
            problems.append(f"{svc.app}: table says no datasource but application.yml declares one")
    elif svc.database not in text:
        problems.append(f"{svc.app}: database {svc.database} not mentioned in application.yml")

    if svc.elasticsearch and "elasticsearch" not in text.lower():
        problems.append(f"{svc.app}: marked elasticsearch but application.yml has no elasticsearch config")
    if svc.clickhouse and "8123" not in text:
        problems.append(f"{svc.app}: marked clickhouse but application.yml has no ClickHouse endpoint")
    return problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="verify the checked-in manifests match the generator")
    args = parser.parse_args()

    root = Path(".").resolve()
    out_dir = root / "deploy" / "k8s"
    if not out_dir.is_dir():
        print(f"error: {out_dir} not found; run from the repo root", file=sys.stderr)
        return 2

    problems: list[str] = []
    stale: list[str] = []
    for svc in SERVICES:
        problems += verify(root, svc)
        content = render(svc)
        target = out_dir / f"{svc.app}.yaml"
        if args.check:
            existing = target.read_text(encoding="utf-8") if target.exists() else ""
            if existing != content:
                stale.append(str(target.relative_to(root)))
        else:
            target.write_text(content, encoding="utf-8")
            print(f"wrote {target.relative_to(root)}")

    if problems:
        print("\nThe generator table disagrees with the services:\n", file=sys.stderr)
        for problem in problems:
            print(f"  - {problem}", file=sys.stderr)
        return 1

    if stale:
        print("\nManifests are out of date (run without --check to regenerate):\n", file=sys.stderr)
        for path in stale:
            print(f"  - {path}", file=sys.stderr)
        return 1

    if args.check:
        print(f"{len(SERVICES)} ecom manifests are up to date.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
